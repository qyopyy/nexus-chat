function pieceFrom(
  day: number,
  kind: PromoKind,
  raw: DayPack["story"],
): PromoPiece {
  return {
    id: `d${day}-${kind}`,
    day,
    kind,
    title: raw.title,
    hook: raw.hook,
    caption: raw.caption,
    cta: raw.cta,
    overlays: raw.overlays,
    shots: raw.shots,
    durationSec: raw.durationSec,
    music: raw.music,
    hashtags: [...BASE_TAGS, ...raw.tags],
  };
}

/** Day index 1–30 from a date (or offset days from today). */
export function promoDayNumber(date = new Date()): number {
  // Stable rotating day 1..30 from unix days
  const n = Math.floor(date.getTime() / 86_400_000);
  return (n % DAY_PACKS.length) + 1;
}

export function packForDay(day: number): { theme: string; pieces: PromoPiece[] } {
  const idx = ((Math.floor(day) - 1) % DAY_PACKS.length + DAY_PACKS.length) % DAY_PACKS.length;
  const pack = DAY_PACKS[idx]!;
  const d = idx + 1;
  return {
    theme: pack.theme,
    pieces: [pieceFrom(d, "story", pack.story), pieceFrom(d, "reel", pack.reel), pieceFrom(d, "tiktok", pack.tiktok)],
  };
}

/** Deterministic today’s three pieces. */
export function todaysPromos(date = new Date()): PromoPiece[] {
  return packForDay(promoDayNumber(date)).pieces;
}

export function todaysTheme(date = new Date()): string {
  return packForDay(promoDayNumber(date)).theme;
}

export function allPromoPool(): PromoPiece[] {
  return DAY_PACKS.flatMap((pack, i) => {
    const d = i + 1;
    return [pieceFrom(d, "story", pack.story), pieceFrom(d, "reel", pack.reel), pieceFrom(d, "tiktok", pack.tiktok)];
  });
}

export function formatPromo(p: PromoPiece) {
  return `${p.hook}\n\n${p.caption}\n\n${p.cta}\n\n${p.hashtags.join(" ")}`;
}

/** Full filming script for clipboard. */
export function formatPromoScript(p: PromoPiece) {
  return [
    `Nexus promo — Day ${p.day} · ${p.kind.toUpperCase()} · ${p.title}`,
    `Length: ~${p.durationSec}s · Music: ${p.music}`,
    "",
    `HOOK: ${p.hook}`,
    `CAPTION: ${p.caption}`,
    `CTA: ${p.cta}`,
    "",
    "ON-SCREEN TEXT:",
    ...p.overlays.map((o, i) => `  ${i + 1}. ${o}`),
    "",
    "SHOT LIST:",
    ...p.shots.map((s, i) => `  ${i + 1}. ${s}`),
    "",
    p.hashtags.join(" "),
  ].join("\n");
}

export function formatDayPack(day: number) {
  const { theme, pieces } = packForDay(day);
  return [
    `Nexus daily promo pack — Day ${((day - 1) % DAY_PACKS.length) + 1}/30 — ${theme}`,
    "",
    ...pieces.map((p) => `${"─".repeat(28)}\n${formatPromoScript(p)}`),
  ].join("\n\n");
}

