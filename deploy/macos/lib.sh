#!/usr/bin/env bash
# Shared helpers for the macOS deployment scripts. Source it; do not run it.
# shellcheck disable=SC2034 # variables used by the scripts that source this file

# The project name in one place: the service user, the launchd labels and the config folder.
APP_ID="${PLAYGTA_APP_ID:-playgta}"
LABEL_PREFIX="${PLAYGTA_LABEL_PREFIX:-local.$APP_ID}"
SERVICES=(video server chiaki kick tunnel)

# Parameter expansion instead of dirname(1): sandboxed scripts may not exec it.
_lib_dir="${BASH_SOURCE[0]%/*}"; [[ "$_lib_dir" == "${BASH_SOURCE[0]}" ]] && _lib_dir=.
DEPLOY_DIR="$(cd "$_lib_dir" && pwd)"; unset _lib_dir
REPO_ROOT="$(cd "$DEPLOY_DIR/../.." && pwd)"
CONFIG_DIR="$HOME/Library/Application Support/$APP_ID"
LOG_DIR="$HOME/Library/Logs/$APP_ID"
AGENTS_DIR="$HOME/Library/LaunchAgents"
# ~/.bun/bin is where the official Bun installer puts bun; Homebrew's (oven-sh/bun/bun) comes first.
SERVICE_PATH="/opt/homebrew/bin:/opt/homebrew/sbin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin:$HOME/.bun/bin"

# Settings files. PLAYGTA_ENV_FILE overrides the repo's .env (dry runs and tests only).
ENV_FILE="${PLAYGTA_ENV_FILE:-$REPO_ROOT/.env}"
SERVER_ENV="$CONFIG_DIR/server.env"
KICK_ENV="$CONFIG_DIR/kick.env"
TUNNEL_ENV="$CONFIG_DIR/tunnel.env"

# Prints the value of KEY from $ENV_FILE (last assignment wins) without executing the file.
# Surrounding single or double quotes are removed.
env_value() {
  local key="$1" file="$ENV_FILE" line value=""
  [[ -f "$file" ]] || return 0
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line#"${line%%[![:space:]]*}"}"
    line="${line#export }"
    if [[ "$line" == "$key="* ]]; then
      value="${line#"$key="}"
      value="${value%"${value##*[![:space:]]}"}"
      if [[ "$value" =~ ^\"(.*)\"$ || "$value" =~ ^\'(.*)\'$ ]]; then value="${BASH_REMATCH[1]}"; fi
    fi
  done <"$file"
  printf '%s' "$value"
}

# setting KEY: the repo's .env first, then server.env (secrets kept outside the repo).
setting() {
  local value
  value="$(env_value "$1")"
  [[ -n "$value" ]] || value="$(ENV_FILE="$SERVER_ENV" env_value "$1")"
  printf '%s' "$value"
}

log() { echo "$(date '+%F %T') $*"; }

xml_escape() {
  local s="$1"
  s="${s//&/&amp;}"; s="${s//</&lt;}"; s="${s//>/&gt;}"; s="${s//\"/&quot;}"
  printf '%s' "$s"
}

# render_template FILE [--xml] KEY=VALUE...: prints FILE with every @KEY@ replaced. With --xml the
# values are XML-escaped. Fails if a placeholder is left unfilled.
render_template() {
  local file="$1" escape=false content pair key value; shift
  [[ "${1:-}" == --xml ]] && { escape=true; shift; }
  # bash 5.2 treats & in a replacement as the match; turn that off where it exists.
  shopt -u patsub_replacement 2>/dev/null || true
  content="$(<"$file")"
  for pair in "$@"; do
    key="${pair%%=*}"; value="${pair#*=}"
    $escape && value="$(xml_escape "$value")"
    content="${content//@${key}@/$value}"
  done
  if [[ "$content" =~ @[A-Z_]+@ ]]; then echo "Unfilled placeholder ${BASH_REMATCH[0]} in $file" >&2; return 1; fi
  printf '%s\n' "$content"
}

# The patched chiaki-ng executable, or nothing if it is not built yet (scripts/build-chiaki.sh).
chiaki_binary() {
  local app
  app="$(find "$REPO_ROOT/vendor/chiaki-ng/build/gui" -maxdepth 1 -name '*.app' 2>/dev/null | head -1)"
  [[ -n "$app" ]] || return 0
  find "$app/Contents/MacOS" -maxdepth 1 -type f -perm -u+x | head -1
}

# Whether a Cloudflare Tunnel can run: a local config or a token in tunnel.env.
tunnel_configured() {
  [[ -f "$HOME/.cloudflared/config.yml" || -n "$(ENV_FILE="$TUNNEL_ENV" env_value CLOUDFLARE_TUNNEL_TOKEN)" ]]
}

# MediaMTX API credentials: generated by install.sh into MEDIAMTX_API_ENV (mode 600) and read by
# the server and these scripts. MediaMTX itself only gets the password's SHA-256.
MEDIAMTX_API_URL="${MEDIAMTX_API_URL:-http://127.0.0.1:9997}"
MEDIAMTX_API_ENV="$CONFIG_DIR/mediamtx-api.env"
MEDIAMTX_API_USER="$APP_ID-api"

ensure_mediamtx_api_env() {
  if [[ ! -s "$MEDIAMTX_API_ENV" ]]; then
    mkdir -p "$CONFIG_DIR"
    (umask 077 && printf 'MEDIAMTX_API_USER=%s\nMEDIAMTX_API_PASS=%s\n' "$MEDIAMTX_API_USER" \
      "$(openssl rand -hex 32)" >"$MEDIAMTX_API_ENV")
  fi
  chmod 600 "$MEDIAMTX_API_ENV"
}

# The form of a password that MediaMTX checks: sha256:<base64 of its SHA-256>.
mediamtx_pass_hash() { printf 'sha256:%s' "$(printf '%s' "$1" | openssl dgst -sha256 -binary | base64)"; }

# mediamtx_api PATH: the API's answer for PATH. The password reaches curl through a pipe, never
# its command line (other users can list processes).
mediamtx_api() {
  local user pass
  user="$(ENV_FILE="$MEDIAMTX_API_ENV" env_value MEDIAMTX_API_USER)"
  pass="$(ENV_FILE="$MEDIAMTX_API_ENV" env_value MEDIAMTX_API_PASS)"
  if [[ -n "$user" ]]; then
    curl -fsS -m 3 -K <(printf 'user = "%s:%s"\n' "$user" "$pass") "$MEDIAMTX_API_URL$1"
  else
    curl -fsS -m 3 "$MEDIAMTX_API_URL$1"
  fi
}

# ---------- standby ----------
# The console itself ended Remote Play (someone picked it up; chiaki-ng logs the reason "Server
# shutting down"). STANDBY_FILE then holds the epoch second when the restream's standby slate ends
# (10 minutes later). While it exists, nothing reconnects to the console (that would
# take it from whoever is holding it) until resume.sh or install.sh clears it.
STANDBY_FILE="$CONFIG_DIR/standby-until"
CHIAKI_LOG="$LOG_DIR/chiaki.log"
STANDBY_CLEARED_MARK="standby cleared"
STANDBY_SECONDS=600

# Reads chiaki-ng log text on stdin; succeeds when the last disconnect was the console ending it.
console_ended() {
  awk -v cleared="$STANDBY_CLEARED_MARK" '
    /chiaki-ng binary: / || index($0, cleared) { ended = 0 }
    /Remote disconnected from StreamConnection with reason "/ { ended = index($0, "reason \"Server shutting down\"") > 0 }
    END { exit !ended }'
}

standby_active() { [[ -f "$STANDBY_FILE" ]]; }

standby_enter() {
  standby_active && return 0
  mkdir -p "$CONFIG_DIR" && printf '%s\n' "$(($1 + STANDBY_SECONDS))" >"$STANDBY_FILE.tmp" && mv -f "$STANDBY_FILE.tmp" "$STANDBY_FILE"
}

standby_until() {
  local until=""
  [[ -f "$STANDBY_FILE" ]] && read -r until <"$STANDBY_FILE"
  [[ "$until" =~ ^[0-9]+$ ]] || until=0
  printf '%s' "$until"
}

standby_left() {
  local left=$(($(standby_until) - $1))
  ((left > 0)) || left=0
  printf '%s' "$left"
}

standby_clear() {
  rm -f "$STANDBY_FILE"
  [[ -d "$LOG_DIR" ]] && echo "$(date '+%F %T') $STANDBY_CLEARED_MARK" >>"$CHIAKI_LOG"
  return 0
}
